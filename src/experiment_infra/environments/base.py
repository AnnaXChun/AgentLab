from typing import Protocol

from experiment_infra.core.schema import EnvironmentSpec
from packages.sandbox.base import Command, ExecutionResult


class EnvironmentBackend(Protocol):
    """observe returns provider metadata with spec (EnvironmentSpec JSON), fingerprint,
    and optional snapshot_mime_type. Runtime never interprets provider image internals.
    """

    async def create(self, spec: EnvironmentSpec) -> str: ...
    async def execute(self, handle: str, action: Command) -> ExecutionResult: ...
    async def upload(self, handle: str, path: str, data: bytes) -> None: ...
    async def download(self, handle: str, path: str) -> bytes: ...
    async def observe(self, handle: str) -> dict: ...
    async def snapshot(self, handle: str) -> bytes: ...
    async def restore(self, handle: str, snapshot: bytes) -> None: ...
    def diff(self, snapshot_a: bytes, snapshot_b: bytes) -> dict: ...
    async def destroy(self, handle: str) -> None: ...
